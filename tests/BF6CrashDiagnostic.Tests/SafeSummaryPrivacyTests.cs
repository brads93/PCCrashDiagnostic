    private static IEnumerable<MemberInfo> ReadReferencedMembers(MethodBase method)
    {
        byte[]? il = method.GetMethodBody()?.GetILAsByteArray();
        if (il is null)
        {
            yield break;
        }

        int offset = 0;
        while (offset < il.Length)
        {
            ushort value = il[offset++];
            if (value == 0xFE)
            {
                value = (ushort)(0xFE00 | il[offset++]);
            }

            if (!OpCodesByValue.TryGetValue(value, out OpCode opcode))
            {
                throw new InvalidDataException($"Unknown IL opcode 0x{value:X4} in {method.Name}.");
            }

            int operandOffset = offset;
            int operandSize = OperandSize(opcode.OperandType, il, operandOffset);
            if (opcode.OperandType is OperandType.InlineField or OperandType.InlineMethod or OperandType.InlineTok)
            {
                int token = BitConverter.ToInt32(il, operandOffset);
                MemberInfo? member = null;
                try
                {
                    member = method.Module.ResolveMember(
                        token,
                        method.DeclaringType?.GetGenericArguments(),
                        method.IsGenericMethod ? method.GetGenericArguments() : null);
                }
                catch (ArgumentException)
                {
                    // An unresolved generic token cannot name one of the concrete model getters above.
                }

                if (member is not null)
                {
                    yield return member;
                }
            }

            offset += operandSize;
        }
    }

    private static int OperandSize(OperandType operandType, byte[] il, int offset) => operandType switch
    {
        OperandType.InlineNone => 0,
        OperandType.ShortInlineBrTarget or OperandType.ShortInlineI or OperandType.ShortInlineVar => 1,
        OperandType.InlineVar => 2,
        OperandType.InlineBrTarget or OperandType.InlineField or OperandType.InlineI or
            OperandType.InlineMethod or OperandType.InlineSig or OperandType.InlineString or
            OperandType.InlineTok or OperandType.InlineType or OperandType.ShortInlineR => 4,
        OperandType.InlineI8 or OperandType.InlineR => 8,
        OperandType.InlineSwitch => 4 + checked(BitConverter.ToInt32(il, offset) * 4),
        _ => throw new InvalidDataException($"Unsupported IL operand type {operandType}.")
    };

    private static readonly IReadOnlyDictionary<ushort, OpCode> OpCodesByValue = typeof(OpCodes)
        .GetFields(BindingFlags.Public | BindingFlags.Static)
        .Where(field => field.FieldType == typeof(OpCode))
        .Select(field => (OpCode)field.GetValue(null)!)
        .ToDictionary(opcode => unchecked((ushort)opcode.Value));
}
