        Assert.DoesNotContain(new string('b', 64), text, StringComparison.OrdinalIgnoreCase);
        Assert.Equal(BuildProfile.Version, summary.GeneratorVersion);
        Assert.Equal(BuildProfile.Current.Profile, summary.GeneratorProfile);
        Assert.Equal(SafeSummaryTestData.Create().ToolVersion, summary.SourceReportVersion);
        Assert.Contains($"Generated by: PC Crash Diagnostic {BuildProfile.Version}", text, StringComparison.Ordinal);
        Assert.Contains($"Build profile: {BuildProfile.Current.Profile}", text, StringComparison.Ordinal);
        Assert.Contains("Bugcheck 0x00000116 (VIDEO_TDR_FAILURE)", text, StringComparison.Ordinal);
        Assert.Contains("WHEA event 18", text, StringComparison.Ordinal);
        Assert.Contains("WHEA event 18: Fatal, count 3.", text, StringComparison.Ordinal);
        Assert.Contains("Application crash marker", text, StringComparison.Ordinal);
        Assert.Contains("64.0 GiB", text, StringComparison.Ordinal);
        Assert.Contains("KB5030219", text, StringComparison.Ordinal);
        Assert.Contains("VIDEO_TDR_FAILURE_nvlddmkm!unknown_function", text, StringComparison.Ordinal);
        Assert.Contains("nvlddmkm.sys", text, StringComparison.Ordinal);
        Assert.Contains("Selected time (UTC): 2026-08-16 12:36Z", text, StringComparison.Ordinal);
        Assert.DoesNotContain("2026-08-16 12:34Z", text, StringComparison.Ordinal);
        Assert.DoesNotContain("2026-08-16 12:39Z", text, StringComparison.Ordinal);
        Assert.True(summary.ValuesWereOmitted);
        Assert.True(bytes.Length <= SafeSummaryRenderer.MaximumUtf8Bytes);
        Assert.False(bytes.AsSpan().StartsWith(Encoding.UTF8.Preamble));
        Assert.Equal(text, SafeSummaryRenderer.Render(SafeSummaryProjector.Project(SafeSummaryTestData.Create())));
    }

