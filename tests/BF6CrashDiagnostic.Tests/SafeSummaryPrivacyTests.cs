    [Fact]
    public void SharingAssembly_DoesNotReferenceForbiddenFreeFormReportGetters()
    {
        var forbidden = new HashSet<(Type Type, string Getter)>
        {
            (typeof(DiagnosticEvent), "get_Message"),
            (typeof(DiagnosticEvent), "get_Data"),
            (typeof(DuplicateEventGroup), "get_Message"),
            (typeof(ReliabilityRecord), "get_Message"),
            (typeof(CollectionStatus), "get_Detail"),
            (typeof(DiagnosticReportV3), "get_Summary"),
            (typeof(DiagnosticFinding), "get_Title"),
            (typeof(DiagnosticFinding), "get_Evidence"),
            (typeof(DiagnosticFinding), "get_Meaning"),
            (typeof(DiagnosticFinding), "get_DoesNotProve"),
            (typeof(DiagnosticFinding), "get_NextCheck")
        };
        Assembly assembly = typeof(SafeSummaryProjector).Assembly;
        MethodInfo[] sharingMethods = assembly.GetTypes()
            .Where(type => type.Namespace == typeof(SafeSummaryProjector).Namespace)
            .SelectMany(type => type.GetMethods(
                BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Static | BindingFlags.Instance |
                BindingFlags.DeclaredOnly))
            .ToArray();

        var violations = new List<string>();
        foreach (MethodInfo method in sharingMethods)
        {
            foreach (MemberInfo member in ReadReferencedMembers(method))
            {
                if (member is MethodInfo referenced &&
                    referenced.DeclaringType is not null &&
                    forbidden.Contains((referenced.DeclaringType, referenced.Name)))
                {
                    violations.Add($"{method.DeclaringType?.FullName}.{method.Name} -> {referenced.DeclaringType.Name}.{referenced.Name}");
                }
            }
        }

        Assert.Empty(violations);
    }

    [Fact]
    public void ProjectAndRender_ExcludeFreeFormAndSensitiveFields()
    {
        SafeSummaryV1 summary = SafeSummaryProjector.Project(SafeSummaryTestData.Create());
        string text = SafeSummaryRenderer.Render(summary);
        byte[] bytes = SafeSummaryRenderer.RenderUtf8(summary);

        Assert.DoesNotContain(SafeSummaryTestData.Canary, text, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("C:\\Users\\Alice", text, StringComparison.OrdinalIgnoreCase);
